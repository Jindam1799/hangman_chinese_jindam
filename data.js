const toneMap = {
    'a': ['ā', 'á', 'ǎ', 'à', 'a'], 'e': ['ē', 'é', 'ě', 'è', 'e'],
    'i': ['ī', 'í', 'ǐ', 'ì', 'i'], 'o': ['ō', 'ó', 'ǒ', 'ò', 'o'],
    'u': ['ū', 'ú', 'ǔ', 'ù', 'u'], 'v': ['ǖ', 'ǘ', 'ǚ', 'ǜ', 'ü'] 
};

function getBaseChar(char) {
    for (let base in toneMap) { if (toneMap[base].includes(char)) return base; }
    return char;
}
